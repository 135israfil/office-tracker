"""Activity sessions (§18).

One row is a *closed interval* — "Chrome was in the foreground from 09:14:02 to
09:31:40" — never a per-second sample. That is the difference between a few hundred
rows per PC per day and a few hundred thousand.

The tracks run in parallel and nothing sums across them: an APPLICATION session, a
WEBSITE session and an ACTIVE session can all cover the same wall-clock minute. Totals
are only ever computed within one `activity_type`.

Phase 4 writes PC_ON sessions only (opened and closed from agent heartbeats and
lifecycle events). Phase 5 adds the agent-side session builder that produces the
ACTIVE / IDLE / APPLICATION tracks, and Phase 6 adds WEBSITE.
"""

from __future__ import annotations

import uuid

from django.db import models


class ActivityType(models.TextChoices):
    PC_ON = "PC_ON", "PC on"
    PC_OFF = "PC_OFF", "PC off"
    ACTIVE = "ACTIVE", "Active"
    IDLE = "IDLE", "Idle"
    APPLICATION = "APPLICATION", "Application"
    WEBSITE = "WEBSITE", "Website"


class Activity(models.Model):
    """A closed (or currently open) session of one kind of activity."""

    employee = models.ForeignKey(
        "employees.Employee", on_delete=models.CASCADE, related_name="activities"
    )
    computer = models.ForeignKey(
        "computers.Computer", on_delete=models.CASCADE, related_name="activities"
    )

    activity_type = models.CharField(max_length=16, choices=ActivityType.choices)

    application_name = models.CharField(max_length=200, blank=True)
    executable_name = models.CharField(max_length=200, blank=True)
    # Domain only, never a URL (§16, §17). Enforced in the agent's browser collector,
    # which truncates before anything is written to disk or sent over the network.
    website_domain = models.CharField(max_length=253, blank=True)

    start_time = models.DateTimeField()
    # Null while the session is still open. A session left open by a crash is closed
    # server-side at the last heartbeat rather than left dangling forever.
    end_time = models.DateTimeField(null=True, blank=True)
    duration_seconds = models.PositiveIntegerField(default=0)

    # Generated by the agent (or by the server for sessions it infers). Unique per
    # computer, which is the entire anti-duplicate mechanism §19 asks for: sync is an
    # upsert on (computer, client_event_id), so replaying a batch after a dropped
    # response is harmless by construction.
    client_event_id = models.UUIDField(default=uuid.uuid4)

    # True when the server closed this session by inference (missed heartbeats) rather
    # than because the agent reported an end. Worth keeping: it is the difference
    # between "the PC was shut down at 18:05" and "the PC stopped answering at 18:05".
    closed_by_server = models.BooleanField(default=False)

    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ["-start_time", "-id"]
        constraints = [
            models.UniqueConstraint(
                fields=["computer", "client_event_id"], name="unique_event_per_computer"
            )
        ]
        indexes = [
            models.Index(fields=["employee", "start_time"]),
            models.Index(fields=["computer", "activity_type", "start_time"]),
            # Finding the open session for a computer happens on every heartbeat.
            models.Index(
                fields=["computer", "activity_type"],
                condition=models.Q(end_time__isnull=True),
                name="activity_open_session_idx",
            ),
        ]
        verbose_name_plural = "activities"

    def __str__(self):
        end = self.end_time.isoformat() if self.end_time else "open"
        return f"{self.computer_id} {self.activity_type} {self.start_time.isoformat()}..{end}"

    def close(self, end_time, *, by_server: bool = False):
        """Close the session, clamping a negative duration to zero.

        A clock that steps backwards (NTP correction, a VM resuming from a snapshot)
        must not produce a negative or absurd duration.
        """
        if end_time < self.start_time:
            end_time = self.start_time
        self.end_time = end_time
        self.duration_seconds = int((end_time - self.start_time).total_seconds())
        self.closed_by_server = by_server
        self.save(update_fields=["end_time", "duration_seconds", "closed_by_server"])
        return self
